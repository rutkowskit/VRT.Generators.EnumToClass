using EnumToClass.Helpers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Text;

#pragma warning disable IDE0130 // Namespace does not match folder structure
namespace VRT.Generators;
#pragma warning restore IDE0130 // Namespace does not match folder structure

[Generator]
public class EnumToClassGenerator : IIncrementalGenerator
{
    private const string EndOfLine = "\r\n";
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // _ = System.Diagnostics.Debugger.Launch();
        // add attribute source code to calling assembly        
        context.RegisterPostInitializationOutput(static ctx =>
        {
            ctx.AddSource(
                hintName: $"{EnumToClassAttributeDefinition.AttributeTypeName}.g.cs",
                source: EnumToClassAttributeDefinition.SourceCode);
        });

        var pipeline = context.SyntaxProvider.ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: EnumToClassAttributeDefinition.FullyQualifiedName,
            predicate: static (syntaxNode, _) => syntaxNode is TypeDeclarationSyntax,
            transform: static (ctx, _) =>
            {
                var classDecl = ctx.TargetSymbol as INamedTypeSymbol;
                return EnumToClassData.FromClass(classDecl);
            })
            .Where(n => n is not null);

        // Generate the partial class for each matched class
        context.RegisterSourceOutput(pipeline, static (ctx, model) =>
        {
            if (model!.IsNested)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(
                    EnumToClassDiagnostics.NestedTypeNotSupported,
                    model.Location,
                    model.ClassName,
                    model.ContainingTypeName));
                return;
            }

            if (model.IsPartial is false)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(
                    EnumToClassDiagnostics.TypeMustBePartial,
                    model.Location,
                    model.ClassName));
                return;
            }

            if (model.GetEnumFields().Count == 0)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(
                    EnumToClassDiagnostics.EnumHasNoMembers,
                    model.Location,
                    model.ClassName));
            }

            foreach (var pending in model.PendingDiagnostics)
            {
                var descriptor = EnumToClassDiagnostics.TryGetDescriptor(pending.DescriptorId);
                if (descriptor is null)
                {
                    continue;
                }

                ctx.ReportDiagnostic(Diagnostic.Create(
                    descriptor,
                    model.Location,
                    pending.MessageArgs.Cast<object>().ToArray()));
            }

            var classSource = GenerateCodeForEnumMembers(model);
            ctx.AddSource($"{model.ClassName}_Constants.g.cs", SourceText.From(classSource, Encoding.UTF8));

            var constructorSource = GeneratePropertiesAndConstructor(model);
            ctx.AddSource($"{model.ClassName}_Constructors.g.cs", SourceText.From(constructorSource, Encoding.UTF8));
        });
    }

    private static string GeneratePropertiesAndConstructor(EnumToClassData data)
    {
        var code = $$"""
            // <auto-generated />
            #nullable enable
            namespace {{data.ClassNamespace}}
            {
                {{data.GetPartialDeclarationWithInterfaces()}}
                {
                    {{data.GetConstructorDeclaration()}}
                    {
                        Name = value.ToString();
                        IsEmpty = value == default({{data.EnumTypeFullName}});
                        Value = value;
                        {{data.GetDescriptionFieldInitialization()}}
                    }
                    public string Name { get; }
                    public {{data.EnumTypeFullName}} Value { get; }
                    public bool IsEmpty { get; }

                    {{data.GetDescriptionFieldDeclaration()}}
                    {{string.Join($"{EndOfLine}                    ", data.GetAttributePropertyDeclarationLines())}}
                    {{GenerateEqualityMembers(data)}}

                    public override string ToString() => Name;

                    public static global::System.Collections.Generic.IReadOnlyCollection<{{data.ClassName}}> GetAll() => ValueByNameMap.Values;

                    public static global::System.Collections.Generic.IEnumerable<{{data.ClassName}}> GetByName(global::System.Collections.Generic.IEnumerable<string> names)
                        => global::System.Linq.Enumerable.Where(global::System.Linq.Enumerable.Select(names, GetByName), static p => p.IsEmpty == false);

                    public static {{data.ClassName}} GetByName(string name)
                    {
                        return ValueByNameMap.TryGetValue(name, out var value)
                            ? value
                            : Empty;
                    }

                    public static bool TryGetByName(string name, out {{data.ClassName}} value)
                    {
                        if (ValueByNameMap.TryGetValue(name, out value!))
                        {
                            return true;
                        }

                        value = Empty;
                        return false;
                    }

                    public static implicit operator {{data.ClassName}}(string name) => GetByName(name);
                    public static implicit operator string({{data.ClassName}} value) => value.Name;
                    public static implicit operator {{data.EnumTypeFullName}}({{data.ClassName}} value) => value.Value;
                    public static implicit operator {{data.ClassName}}({{data.EnumTypeFullName}} value) => GetByName(value.ToString());
                    public static implicit operator {{data.EnumTypeUnderlyingTypeName}}({{data.ClassName}} value) => ({{data.EnumTypeUnderlyingTypeName}}) value.Value;
                    public static implicit operator {{data.ClassName}}({{data.EnumTypeUnderlyingTypeName}} value) => ({{data.EnumTypeFullName}})value;
                }
            }
            """;
        return code;
    }
    private static string GenerateEqualityMembers(EnumToClassData classSymbol)
    {
        return classSymbol switch
        {
            { IsRecord: true } => "",
            _ => $$"""
                   public bool Equals({{classSymbol.ClassName}}? other)
                       => other is not null && other.Value == Value;

                   public override bool Equals(object? obj)
                       => obj is {{classSymbol.ClassName}} other && Equals(other);

                   public override int GetHashCode() => Value.GetHashCode();

                   public static bool operator ==({{classSymbol.ClassName}}? left, {{classSymbol.ClassName}}? right)
                       => left is null ? right is null : left.Equals(right);

                   public static bool operator !=({{classSymbol.ClassName}}? left, {{classSymbol.ClassName}}? right)
                       => !(left == right);
                   """
        };
    }
    private static string GenerateCodeForEnumMembers(EnumToClassData data)
    {
        string className = data.ClassName;

        return $$"""
            // <auto-generated />
            #nullable enable

            namespace {{data.ClassNamespace}}
            {
                {{data.GetPartialDeclarationWithInterfaces()}}
                {
                    private static readonly global::System.Collections.ObjectModel.ReadOnlyDictionary<string, {{className}}> ValueByNameMap = new global::System.Collections.ObjectModel.ReadOnlyDictionary<string, {{className}}>(new global::System.Collections.Generic.Dictionary<string, {{className}}>()
                    {
                        {{string.Join($",{EndOfLine}            ", ToDictionaryEntries(data))}}
                    });

                    {{data.GetEmptyItemDefinition()}}

                    {{string.Join($"{EndOfLine}        ", ToConstDeclaration(data))}}

                    {{string.Join($"{EndOfLine}        ", ToInstanceDeclaration(data))}}
                }
            }
            """;
    }
    private static IEnumerable<string> ToDictionaryEntries(EnumToClassData data)
    {
        foreach (var member in data.GetEnumFields())
        {
            yield return $"[{CodeLiteral.String(member.Name)}] = {data.GetClassConstruction(member)}";
        }
    }

    private static IEnumerable<string> ToConstDeclaration(EnumToClassData data)
    {
        foreach (var member in data.GetEnumFields())
        {
            foreach (var docLine in DocumentationFormatter.ToDocumentationLines(member.DocumentationComment))
            {
                yield return docLine;
            }

            yield return $"public const string {member.Name} = {CodeLiteral.String(member.Name)};";
        }
    }

    private static IEnumerable<string> ToInstanceDeclaration(EnumToClassData data)
    {
        foreach (var member in data.GetEnumFields())
        {
            foreach (var docLine in DocumentationFormatter.ToDocumentationLines(member.DocumentationComment))
            {
                yield return docLine;
            }

            yield return $"public static {data.ClassName} {member.Name}Instance {{ get; }} = ValueByNameMap[{CodeLiteral.String(member.Name)}];";
        }
    }
}
